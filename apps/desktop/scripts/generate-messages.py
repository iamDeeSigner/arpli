#!/usr/bin/env python3
"""Generate src/shared/paraglide/messages.ts from messages/en.json.

The UI kit ported from Intent (cloudlands-fe) reads its strings through Paraglide
(`import { m } from '$shared/paraglide/messages.js'`). Arpli is English-only for now,
so instead of the Paraglide compiler we emit one typed function per message key
that the source actually uses. Re-run after porting components that use new keys (copy any missing keys from
cloudlands-fe/messages/en.json first):

    python3 scripts/generate-messages.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
catalog = json.loads((ROOT / 'messages/en.json').read_text())

used = set()
for path in (ROOT / 'src').rglob('*'):
    if path.suffix not in {'.ts', '.svelte'} or 'paraglide' in path.parts:
        continue
    used.update(re.findall(r'\bm\.([A-Za-z0-9_]+)\b', path.read_text()))

missing = sorted(k for k in used if k not in catalog)
keys = sorted(k for k in used if k in catalog)

out = [
    '// Generated by scripts/generate-messages.py from messages/en.json. Do not edit by hand.',
    '/* eslint-disable */',
    '',
]
for key in keys:
    text = catalog[key]
    params = sorted(set(re.findall(r'\{([A-Za-z0-9_]+)\}', text)))
    literal = json.dumps(text)
    if params:
        sig = '{ ' + '; '.join(f'{p}: unknown' for p in params) + ' }'
        body = literal
        for p in params:
            body = f'{body}.replaceAll({json.dumps("{" + p + "}")}, String(params.{p}))'
        out.append(f'export const {key} = (params: {sig}): string => {body};')
    else:
        out.append(f'export const {key} = (_params?: Record<string, never>): string => {literal};')

out += ['', 'export const m = {', *[f'  {k},' for k in keys], '};', '']
dest = ROOT / 'src/shared/paraglide/messages.ts'
dest.parent.mkdir(parents=True, exist_ok=True)
dest.write_text('\n'.join(out))
print(f'{len(keys)} messages written to {dest.relative_to(ROOT)}')
if missing:
    print('Missing from en.json:', ', '.join(missing))
